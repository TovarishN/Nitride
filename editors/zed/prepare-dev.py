#!/usr/bin/env python3
"""Prepare a Zed dev extension with a reproducible local grammar Git revision.

Only the output directory is changed; the Nitride checkout is never committed.
Python 3.11+ and Git are required. Generated parser sources are checked in.
"""
import argparse
from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parent
MARKER = ".nitride-zed-dev"


def git(directory, *args):
    return subprocess.check_output(
        ["git", "-c", "user.name=Nitride Zed development", "-c",
         "user.email=nitride-zed@localhost", "-c", "commit.gpgsign=false",
         "-c", "core.hooksPath=/dev/null", "-c", "core.autocrlf=false", *args],
        cwd=directory, text=True,
    ).strip()


def prepare(output):
    output = output.resolve()
    if output == ROOT or output in ROOT.parents or output.is_relative_to(ROOT / "tree-sitter-nitride") or output.is_relative_to(ROOT / "languages") or output.is_relative_to(ROOT / "src"):
        raise ValueError("output must not overwrite extension source directories")
    if output.exists() and not (output / MARKER).is_file():
        raise ValueError(f"refusing to change an unmanaged output directory: {output}")
    output.mkdir(parents=True, exist_ok=True)
    (output / MARKER).write_text("Generated by Nitride prepare-dev.py\n")
    for name in ("Cargo.toml", "Cargo.lock", "LICENSE", "README.md"):
        shutil.copy2(ROOT / name, output / name)
    for name in ("src", "languages"):
        shutil.copytree(ROOT / name, output / name, dirs_exist_ok=True)

    # Zed always checks grammars out with Git, even for dev extensions. Make a
    # private source snapshot so uncommitted parser edits can be installed too.
    snapshot = output / "grammar-source"
    snapshot.mkdir(exist_ok=True)
    for name in ("grammar.js", "tree-sitter.json"):
        shutil.copy2(ROOT / "tree-sitter-nitride" / name, snapshot / name)
    for name in ("src", "queries"):
        shutil.copytree(ROOT / "tree-sitter-nitride" / name, snapshot / name, dirs_exist_ok=True)
    (snapshot / ".gitattributes").write_text("* text=auto eol=lf\n")
    if not (snapshot / ".git").exists():
        git(snapshot, "init", "--quiet")
    git(snapshot, "add", "--all")
    if git(snapshot, "diff", "--cached", "--name-only"):
        git(snapshot, "commit", "--quiet", "-m", "Snapshot Nitride editor grammar")
    revision = git(snapshot, "rev-parse", "HEAD")
    manifest = (ROOT / "extension.toml").read_text().split("[grammars.nitride]", 1)[0]
    manifest += (f'[grammars.nitride]\nrepository = "{snapshot.as_uri()}"\n'
                 f'rev = "{revision}"\n')
    (output / "extension.toml").write_text(manifest)
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "target/dev-extension")
    args = parser.parse_args()
    try:
        output = prepare(args.output)
    except (ValueError, OSError, subprocess.CalledProcessError) as error:
        parser.exit(1, f"Cannot prepare Nitride Zed extension: {error}\n")
    print(f"In Zed, run 'zed: install dev extension' and select:\n{output}")


if __name__ == "__main__":
    main()
