"""Generate development-only C# catalog metadata for Nitrogen's editor loader."""
import json
from reference import ROOT

for profile, class_name, output in [("portable", "PortableLanguage", "PortableSemantics.cs"), ("power", "PowerLanguage", "PowerSemantics.cs"), ("namespaces", "NamespacesLanguage", "NamespacesSemantics.cs")]:
    catalog = json.loads((ROOT / f"languages/{profile}/catalog.json").read_text())
    names = {ty: f"T{i}" for i, ty in enumerate(catalog["types"])}
    lines = ["// Generated by scripts/editor_metadata.py; edit catalog.json instead.", "using Nitrogen.Semantic;", "namespace Nitride.Reference.Syntax;", f"public static class {class_name}", "{"]
    for ty, name in names.items():
        module, local = ty.rsplit(".", 1)
        lines.append(f"    static readonly SemanticType {name} = SemanticType.Named({json.dumps(module)}, {json.dumps(local)});")
    lines.append('    public static readonly SemanticModule Semantics = new("Portable", [], [' + ", ".join(names.values()) + "], [")
    for op in catalog["operations"]:
        args = ", ".join([json.dumps(op["id"]), names[op["result"]]] + [names[t] for t in op["inputs"]])
        lines.append(f"        new OperationSignature({args}),")
    lines += ["    ]);", "}"]
    (ROOT / f"languages/{profile}/{output}").write_text("\n".join(lines) + "\n")
