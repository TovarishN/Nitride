"""Generate the explicit .NET reference semantics for Dates; never used by native builds."""
import hashlib
import json
from test_reference import ROOT, catalog_json


def line(source, marker):
    return next(l for l in source.splitlines() if marker in l)


def main():
    folder=ROOT/'languages/dates'; source=(folder/'Dates.ngr').read_text()
    catalog=catalog_json(folder/'Dates.ncatalog')
    source=source.replace('symbols { value }','symbols { value }\n  symbol property Type for value : Nitrogen.Semantic.SemanticType? = DatesLanguage.Builtin(name);')
    old=line(source,'syntax Let =');source=source.replace(old,old[:-1]+' { symbol.Type = Value.Type; }')
    source=source.replace('extensible syntax Expr\n  {','extensible syntax Expr\n  {\n    out Type : Nitrogen.Semantic.SemanticType? = null;\n    out Selected : Nitrogen.Semantic.OperationSignature? = null;')
    results={op['id']:op['result'] for op in catalog['operations']}
    for name in ['Num','Ref','Paren','Days','InDays','Day']:
        old=line(source,f'| {name} =')
        if name=='Num': body='Type = DatesLanguage.Scalar;'
        elif name=='Ref': old,body=old,'Type = Symbol?.Type;'
        elif name=='Paren': body='Type = Inner.Type;'
        else:
            target=old.split('lowers ')[1].split('(')[0]
            body=f'Type = DatesLanguage.Type({json.dumps(results[target])});'
        checks=catalog.get('checks',{}).get('Dates.'+name,[])
        for check in checks:
            body+=f' check {check["code"]} DatesLanguage.Check({json.dumps(check["predicate"])}, {check["field"]}.Text) : {json.dumps(check["message"])};'
        extra=' lowers reference type Type' if name=='Ref' else ''
        source=source.replace(old,old+extra+' { '+body+' }')
    for group in catalog['overloads']:
        old=line(source,f'lowers {group}(')
        args=old.split(f'lowers {group}(')[1].rstrip(')').split(', ')
        new=old.replace(f'lowers {group}(',f'lowers operation? Selected(')+f'''
      {{
        Selected = DatesLanguage.Select({json.dumps(group)}, {", ".join(a+".Type" for a in args)});
        Type = Selected?.Result;
        check DATE0002 Selected != null : "no exact overload";
      }}'''
        source=source.replace(old,new)
    (folder/'Dates.Reference.ngr').write_text('// Generated by scripts/dates_adapter.py; development reference only.\n'+source)
    ids={t:'T'+str(i) for i,t in enumerate(catalog['types'])}
    lines=['// Generated by scripts/dates_adapter.py; explicit reference/editor contract.','using System.Globalization;','using Nitrogen.Semantic;','namespace Nitride.Reference.Dates;','public static class DatesLanguage','{']
    for t,var in ids.items():
        module,name=t.rsplit('.',1);lines.append(f'    static readonly SemanticType {var} = SemanticType.Named({json.dumps(module)}, {json.dumps(name)});')
    lines.append(f'    public static SemanticType Scalar => {ids["Core.Scalar"]};')
    lines.append('    public static SemanticType? Type(string id) => id switch { '+' '.join(f'{json.dumps(t)} => {v},' for t,v in ids.items())+' _ => null };')
    builtins=[(n,t) for names in catalog['values'].values() for n,t in names.items()]
    lines.append('    public static SemanticType? Builtin(string name) => name switch { '+' '.join(f'{json.dumps(n)} => {ids[t["type"]]},' for n,t in builtins)+' _ => null };')
    lines.append('    public static bool Check(string predicate, string text) => predicate == "iso-date" && DateOnly.TryParseExact(text, "yyyy-MM-dd", CultureInfo.InvariantCulture, DateTimeStyles.None, out _);')
    for i,op in enumerate(catalog['operations']):
        args=', '.join([json.dumps(op['id']),ids[op['result']]]+[ids[t] for t in op['inputs']]);lines.append(f'    static readonly OperationSignature O{i} = new({args});')
    opids={op['id']:'O'+str(i) for i,op in enumerate(catalog['operations'])}
    lines+=['    public static OperationSignature? Select(string group, SemanticType? left, SemanticType? right)','    {']
    for group,ops in catalog['overloads'].items():
        lines.append(f'        if (group == {json.dumps(group)}) {{')
        for op in ops:
            v=opids[op];lines.append(f'            if (Equals(left,{v}.Inputs[0]) && Equals(right,{v}.Inputs[1])) return {v};')
        lines.append('        }')
    lines+=['        return null;','    }',f'    public static readonly SemanticModule Semantics = new("Dates", [], [{", ".join(ids.values())}], [{", ".join(opids.values())}]);','}']
    (folder/'DatesSemantics.cs').write_text('\n'.join(lines)+'\n')
    provenance={n:hashlib.sha256((folder/n).read_bytes()).hexdigest() for n in ['Dates.ngr','Dates.ncatalog','Dates.Reference.ngr','DatesSemantics.cs']}
    (folder/'reference-provenance.json').write_text(json.dumps(provenance,indent=2)+'\n')


if __name__=='__main__':main()
