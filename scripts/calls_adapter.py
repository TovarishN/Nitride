"""Generate explicit development-only Nitrogen call semantics and provenance."""
import hashlib
import json
from test_reference import ROOT, catalog_json


def main():
    folder=ROOT/'languages/calls'; source=(folder/'Calls.ngr').read_text()
    source=source.replace('symbols { value function }','symbols { value function }\n  symbol property Type for (value | function) : Nitrogen.Semantic.SemanticType? = null;')
    for name in ['Let','Local']:
        old=next(l for l in source.splitlines() if f'syntax {name} =' in l)
        source=source.replace(old,old[:-1]+' { symbol.Type = Value.Type; }')
    source=source.replace('extensible syntax Expr\n  {','extensible syntax Expr\n  {\n    out Type : Nitrogen.Semantic.SemanticType? = null;\n    out Selected : Nitrogen.Semantic.OperationSignature? = null;')
    for name,body in [('Num','Type = CallsLanguage.Scalar;'),('Ref','Type = Symbol?.Type;'),('Paren','Type = Inner.Type;')]:
        old=next(l for l in source.splitlines() if f'| {name} =' in l)
        extra=' lowers reference type Type' if name=='Ref' else ''
        source=source.replace(old,old+extra+' { '+body+' }')
    catalog=catalog_json(folder/'Calls.ncatalog')
    for rule,policy in catalog['calls'].items():
        name=rule.split('.')[-1];args=policy['args'];old=next(l for l in source.splitlines() if f'| {name} =' in l)
        source=source.replace(old,old+' lowers operation? Selected('+', '.join(args)+')\n      {\n        Selected = Symbol?.IsBuiltin == true ? CallsLanguage.Select(Function.Text, ['+', '.join(a+'.Type' for a in args)+']) : null;\n        Type = Selected?.Result;\n        check CALL0001 Symbol is null || Selected != null : "no exact callable signature";\n      }')
    (folder/'Calls.Reference.ngr').write_text('// Generated by scripts/calls_adapter.py; development reference only.\n'+source)
    ids={t:'T'+str(i) for i,t in enumerate(catalog['types'])}
    lines=['// Generated by scripts/calls_adapter.py; explicit reference/editor contract.','using Nitrogen.Semantic;','namespace Nitride.Reference.Calls;','public static class CallsLanguage','{']
    for t,var in ids.items():
        module,name=t.rsplit('.',1);lines.append(f'    static readonly SemanticType {var} = SemanticType.Named({json.dumps(module)}, {json.dumps(name)});')
    lines.append('    public static SemanticType Scalar => T0;')
    for i,op in enumerate(catalog['operations']):
        args=', '.join([json.dumps(op['id']),ids[op['result']]]+[ids[t] for t in op['inputs']]);lines.append(f'    static readonly OperationSignature O{i} = new({args});')
    opids={op['id']:'O'+str(i) for i,op in enumerate(catalog['operations'])}
    lines+=['    public static OperationSignature? Select(string name, SemanticType?[] args)','    {']
    for name,ops in catalog['builtins']['function'].items():
        lines.append(f'        if (name == {json.dumps(name)}) {{')
        for op in ops:
            v=opids[op];lines.append(f'            if (args.Length == {v}.Inputs.Count && args.Select((a,i) => Equals(a,{v}.Inputs[i])).All(x=>x)) return {v};')
        lines.append('        }')
    lines+=['        return null;','    }',f'    public static readonly SemanticModule Semantics = new("Calls", [], [{", ".join(ids.values())}], [{", ".join(opids.values())}]);','}']
    (folder/'CallsSemantics.cs').write_text('\n'.join(lines)+'\n')
    provenance={n:hashlib.sha256((folder/n).read_bytes()).hexdigest() for n in ['Calls.ngr','Calls.ncatalog','Calls.Reference.ngr','CallsSemantics.cs']}
    (folder/'reference-provenance.json').write_text(json.dumps(provenance,indent=2)+'\n')


if __name__=='__main__':main()
