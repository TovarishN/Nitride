"""Generate the explicit .NET reference semantics; never used by native builds."""
import hashlib
import json
from test_reference import ROOT


def main():
    folder=ROOT/"languages/inference"
    source=(folder/"Inference.ngr").read_text()
    reference=source.replace("symbols { value rate }","symbols { value rate }\n  symbol property Type for (value | rate) : Nitrogen.Semantic.SemanticType? = null;")
    for name in ["LetValue","LetRate"]:
        old=next(line for line in reference.splitlines() if f"syntax {name} =" in line)
        reference=reference.replace(old,old[:-1]+" { symbol.Type = InferenceLanguage.Resolve(Annotation.Text); }")
    for name in ["InferValue","InferRate"]:
        old=next(line for line in reference.splitlines() if f"syntax {name} =" in line)
        reference=reference.replace(old,old[:-1]+" { symbol.Type = Value.Type; }")
    reference=reference.replace("extensible syntax Expr\n  {","extensible syntax Expr\n  {\n    out Type : Nitrogen.Semantic.SemanticType? = null;\n    out Selected : Nitrogen.Semantic.OperationSignature? = null;")
    for name in ["ValueRef","RateRef","AnyRef","ReverseRef"]:
        old=next(line for line in reference.splitlines() if f"| {name} =" in line)
        reference=reference.replace(old,old+" lowers reference type Type { Type = Symbol?.Type; }")
    for name,body in [("Num","Type = InferenceLanguage.Scalar;"),("Paren","Type = Inner.Type;"),("Duration","Type = InferenceLanguage.Time;")]:
        old=next(line for line in reference.splitlines() if f"| {name} =" in line)
        reference=reference.replace(old,old+" { "+body+" }")
    for name in ["Add","Sub"]:
        reference=reference.replace(f"lowers Inference.{name}(Left, Right)",f'''lowers operation? Selected(Left, Right)
      {{
        Selected = InferenceLanguage.Select("Inference.{name}", Left.Type, Right.Type);
        Type = Selected?.Result;
        check INF0001 Selected != null : "no exact overload";
      }}''')
    (folder/"Inference.Reference.ngr").write_text("// Generated by scripts/inference_adapter.py; development reference only.\n"+reference)
    catalog=json.loads((folder/"catalog.json").read_text())
    ids={ty:f"T{i}" for i,ty in enumerate(catalog['types'])}
    lines=['// Generated by scripts/inference_adapter.py; explicit reference/editor contract.',
           'using Nitrogen.Semantic;','namespace Nitride.Reference.Inference;',
           'public static class InferenceLanguage','{']
    for ty,var in ids.items():
        module,name=ty.rsplit('.',1);lines.append(f'    static readonly SemanticType {var} = SemanticType.Named({json.dumps(module)}, {json.dumps(name)});')
    lines+=['    public static SemanticType Scalar => T0;','    public static SemanticType Time => T1;',
            '    public static SemanticType? Resolve(string text) => text switch { "Scalar" => T0, "Time" => T1, _ => null };']
    for i,op in enumerate(catalog['operations']):
        args=', '.join([json.dumps(op['id']),ids[op['result']]]+[ids[t] for t in op['inputs']])
        lines.append(f'    static readonly OperationSignature O{i} = new({args});')
    opids={op['id']:f'O{i}' for i,op in enumerate(catalog['operations'])}
    lines+=['    public static OperationSignature? Select(string group, SemanticType? left, SemanticType? right)','    {']
    for group,ops in catalog['overloads'].items():
        lines.append(f'        if (group == {json.dumps(group)}) {{')
        for op in ops:
            var=opids[op];lines.append(f'            if (Equals(left,{var}.Inputs[0]) && Equals(right,{var}.Inputs[1])) return {var};')
        lines.append('        }')
    lines+=['        return null;','    }',f'    public static readonly SemanticModule Semantics = new("Inference", [], [{", ".join(ids.values())}], [{", ".join(opids.values())}]);','}']
    (folder/"InferenceSemantics.cs").write_text('\n'.join(lines)+'\n')
    provenance={name:hashlib.sha256((folder/name).read_bytes()).hexdigest() for name in ['Inference.ngr','catalog.json','Inference.Reference.ngr','InferenceSemantics.cs']}
    (folder/"reference-provenance.json").write_text(json.dumps(provenance,indent=2)+'\n')


if __name__=='__main__':main()
